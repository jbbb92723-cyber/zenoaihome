function replaceAll(text, pairs) {
  return pairs.reduce((result, [from, to]) => result.split(from).join(to), text);
}

function normalizeTranscript(id, text) {
  let result = text.replace(/\r\n/g, '\n').trim();
  if (id === '7604884601266319689') {
    result = replaceAll(result, traditionalPhrases);
    result = [...result].map((character) => traditionalCharacterMap[character] || character).join('');
  }
  result = replaceAll(result, corrections[id] || []);
  return result;
}

function yamlQuote(value) {
  return JSON.stringify(value);
}

function renderTranscript(video, index) {
  const [id, title, model, status] = video;
  const inputPath = path.join(inputDir, `${id}.txt`);
  if (!fs.existsSync(inputPath)) {
    throw new Error(`Missing transcript: ${inputPath}`);
  }

  const raw = fs.readFileSync(inputPath, 'utf8');
  const transcript = normalizeTranscript(id, raw);
  const caveat = status === '机器原始转写'
    ? '本稿保留机器识别结果，可能含繁简混用、同音字和专名错误；引用前必须回听原视频。'
    : '本稿仅校正可由上下文明确判断的 ASR 错误，未做逐句人工听校；引用前仍应回听原视频。';

  return `---\nsource_id: SRC-EXT-ACC-001\nvideo_id: ${yamlQuote(id)}\ntitle: ${yamlQuote(title)}\nsource_account: ${yamlQuote('西西的思维笔记（siwei9560）')}\nsource_url: ${yamlQuote(`https://www.douyin.com/video/${id}`)}\ncaptured_at: 2026-08-13\ntranscription_engine: whisper.cpp\nmodel: ${model}\ntranscript_status: ${yamlQuote(status)}\nofficial_subtitles: false\n---\n\n# ${String(index + 1).padStart(2, '0')} ${title}\n\n> ${caveat}\n> 外部内容不代表赞诺观点；进入赞诺方法论前，必须经过来源核验、实践验证和证据分级。\n\n## 逐字稿\n\n${transcript}\n`;
}

